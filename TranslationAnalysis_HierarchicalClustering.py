    """ Approach 1: Calculate with N = last frame tracked - first frame tracked """
    """ This approach over estimates the number of positions and thus tracjectories with a smaller
    percentage of tracked positions vs total timesteps yield lower Rg """
    
    # first_frame = np.argmax(~np.isnan(traj[:, 0]))
    # last_frame = np.argwhere(~np.isnan(traj[:, 0]))[-1][0]
    
    # N = last_frame - first_frame
    
    # if N == 0:
    #     return np.nan, np.nan, np.nan, np.nan, np.nan, np.nan, np.nan, np.nan
    
    """ Approach 2: Calculate with N = number positions tracked (i.e.; number of non NaNs) """
    """ This approach should more accurately reperesent the number of positions tracked but may
    in part misrepresent the total time of a trajectory i.e., this method is treating a trajectory
    of length 30 where every frame is tracked the same as a tracjectory of length 100 where only
    30 total frames are tracked """
    
    first_frame = np.argmax(~np.isnan(traj[:, 0]))
    last_frame = np.argwhere(~np.isnan(traj[:, 0]))[-1][0]
    
    N = np.count_nonzero(~np.isnan(traj))
    if N == 0:
        return np.nan, np.nan, np.nan, np.nan, np.nan, np.nan, np.nan, np.nan
    
    # Calculate the Tensor ************************
    
    tensor[0, 0] = (1 / N) * np.nansum((traj[:, 0] - avg_x)**2)
    tensor[0, 1] = (1 / N) * np.nansum((traj[:, 0] - avg_x) * (traj[:, 1] - avg_y))
    tensor[1, 0] = (1 / N) * np.nansum((traj[:, 0] - avg_x) * (traj[:, 1] - avg_y))
    tensor[1, 1] = (1 / N) * np.nansum((traj[:, 1] - avg_y)**2)
    
    # Calculate the Eigen Values **************************
    
    eig_vals, eig_vec = eig(tensor)
    
    R1_squared = eig_vals[0]
    R2_squared = eig_vals[1]
    
    # Unit Conversions *********************************
    
    # t_traj = N * tbf
    
    """ Approach 3: Change use approach 2 for tensor calc but change normalization to account for trajectory length """
    
    t_traj = (last_frame - first_frame) * tbf
    
    Rg = np.sqrt(R1_squared + R2_squared) * pixel_size
    Rg_norm = np.sqrt(R1_squared + R2_squared) * np.sqrt(t_tot / t_traj) * pixel_size
    
    # a2 Computation *********************************
    
    if R1_squared > R2_squared:
        a2 = R2_squared / R1_squared
    else:
        a2 = R1_squared / R2_squared
        
    return Rg, Rg_norm, a2, R1_squared, R2_squared, N, first_frame, last_frame

