def filter_trajectories(traj_arr, num_clusters, num_frames):
    
    """
    Filter Trajectories based on the total number of tracked frames
    when all short trajectories for a molecule are clustered together
    
    Args: 
        traj_arr: (ndarray (movie_len, num_clusters*2)) Hierarchically
            clustered trajectories for each molecule whose linked
            trajectories met the user specified requirements
        num_clusters: (int) Number of clusters found
        num_frames: (int) Number of frames in movie
        
    Returns:
        goodtrajct: (int) Number of trajectories which exceed the specified
            minimum number of frames tracked
        filtered_trajarr: (ndarray (movie_len, goodtrajct*2)) All molecule
            trajectories which exceed the specified minimum number of frames
            tracked. NaN indicate frames for which the molecule could not be
            localized. 
        good_trajinfo: (ndarray, (goodtrajct, 4)): Array with per-trajectory
            information including: 
                - Number of positions tracked
                - Trajectory length (last frame - first frame)
                - Initial frame localized
                - Final frame localized
    """
    
    for i in range(num_clusters):
        
        traj = traj_arr[:, i*2:i*2+2]
        plot_trajpts(traj, i)
    
    num_pos = np.zeros(num_clusters)
    init_frame = np.zeros(num_clusters)
    fin_frame = np.zeros(num_clusters)
    traj_len = np.zeros(num_clusters)

    # Plot trajectory graphs and compute number of tracked frames and length from initial-to-final tracked frame
    for i in range(num_clusters):
        traj = traj_arr[:, i*2:i*2+2]
        num_pos[i] = np.count_nonzero(~np.isnan(traj[:, 0]))    # Shouldn't matter if you check NaN for X or Y coordinate
        
        for j in range(num_frames):
            if ~np.isnan(traj[j, 0]):
                init_frame[i] = j+1
                break
            
        for j in range(num_frames):
            if ~np.isnan(traj[num_frames-j-1, 0]):
                fin_frame[i] = num_frames-j
                break
                
        traj_len = fin_frame - init_frame
    
    traj_info = np.zeros((num_clusters, 4))
    traj_info[:, 0] = num_pos
    traj_info[:, 1] = traj_len 
