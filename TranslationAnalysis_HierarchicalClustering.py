def format_trajs(filename):

    """
    Formats trajectories from Particle Tracker in a way that is easily
    viewable in Excel. 'sfe' = safe for Excel
    
    Args: 
        filename: (str) Filepath location of input trajectories
        
    Returns:
        outname: (str) Filepath of '_sfe' formatted trajectories
    """
    
    out = []
    with open(filename) as file:
        for line in file:
            if "score" in line:
                for line in file:
                    pass # This is to pass the following empty line after "score"
                    for line in file:
                        if "%%" in line:
                            pass
                        else:
                            out.append(line)
                            
    outname = create_saveto_filepath(filename, '_sfe.txt')
    outfile = open(outname, "w+")
    outfile.writelines(out[:-1])
    outfile.close()
    
    return outname

