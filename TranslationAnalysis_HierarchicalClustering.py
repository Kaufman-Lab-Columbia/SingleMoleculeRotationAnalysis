def output_results(Dmsd_arr, Rg_a2_arr, trajarr, num_feats, folder):
    
    """
    Format and output results file
    
    Args: 
        Dmsd_arr: (ndarray (goodtrajct, 3)) Dmsd, fit intercept and fit r^2
            values
        Rg_a2_arr: (ndarray (goodtrajct, 3)) Array of Rg, Rg_norm and a2 values
        trajarr: (ndarray (movie_len, goodtrajct*2)) Array of all linked 
            particle trajectories
        num_feats: (int) Number of molecules with sufficient linked trajectories
        folder: (str) Folder where all files will be written
        
    Returns: 
        None
    """
    
    num_cols = 10
    results = np.zeros((num_feats, num_cols))
    
    # Compute pixel center positions and take average --> relevant for matching to rotations mostly
    
    pix_ctr = np.empty((movie_len, num_feats*2))
    pix_ctr[:] = np.nan
    
    for i in range(movie_len):
        for j in range(num_feats * 2):
            
            if np.isnan(trajarr[i, j]) == True:
                continue
            
            pix_ctr[i, j] = np.rint(trajarr[i, j])
            
    pixctr_filepath = create_saveto_filepath(filename, '_pixel_centers.csv')
    np.savetxt(pixctr_filepath, pix_ctr, delimiter=',')
    
    for i in range(num_feats):
        x_avg = np.nanmean(pix_ctr[:, i*2])
        y_avg = np.nanmean(pix_ctr[:, i*2+1])
            
        results[i, 0] = y_avg
        results[i, 1] = x_avg
    
    results[:, 2:5] = Dmsd_arr
    with np.errstate(invalid='ignore'):
        results[:, 5] = np.log10(Dmsd_arr[:, 0])
    results[:, 6] = np.sqrt(results[:, 3] / 4)
    results[:, 7:] = Rg_a2_arr
    
    # Add median values nad a line of zeros to the array to delineate
    
    empty_add = np.zeros((2, num_cols))
    results = np.append(empty_add, results, axis=0)
    
    for i in range(results.shape[1]):
        results[0, i] = np.nanmedian(results[2:, i])
    
    results_filepath = create_saveto_filepath(filename, '_translation_results.csv')
    np.savetxt(results_filepath, results, delimiter=',', header='Yavg, Xavg, Dmsd, intercept, R^2, logDmsd, Loc. Unc., Rg, Rg_norm, a2')
    
    print('Median log Dmsd: ' + str(results[0, 5]) + '\nMedian Normalized Rg: ' + str(results[0, 8]) + '\nMedian a2: ' + str(results[0, 9]))
    
    return

def QE_Dmsd(msd_vals, MSD_pts):
    
    """ 
    Compute QE MSD and Fit for Dmsd 
    
    Args: 
        msd_vals: (ndarray (MSD_pts, goodtrajct)) Array of all trajectories MSD 
            values
        MSD_pts: (int) Number of MSD pts to fit for Dmsd calculation.  
        
    Returns: 
        None
    """
    
    QE_Dmsd = np.zeros(3,)
    
    QE_MSD = np.mean(msd_vals, axis=1)
    x_data = (np.arange(MSD_pts) + 1) * tbf
    
    res = stats.linregress(x_data, QE_MSD)
    
    QE_Dmsd[0] = res.slope / 4
    QE_Dmsd[1] = res.intercept
    QE_Dmsd[2] = res.rvalue ** 2

    # Plots Fits
    graph_file = create_saveto_filepath(filename, "_QE_Dmsd_Fit.jpg")
    title = 'QE Dmsd Fit'
    fig, ax = plt.subplots(1, 1)
    
    plt.scatter(x_data, QE_MSD, label='MSD Points')
    plt.plot(x_data, res.intercept + res.slope*x_data, 'r', label='QE Dmsd Fit')
    
    plt.xlabel('Time Lag (s)')
    plt.ylabel('QE MSD')
    plt.title(title)


    txt_str = 'm =' + str(res.slope)[0:5] + '\n' + 'b =' + str(res.intercept)[0:5] + '\n' + r'$r^{2} =$' + str(res.rvalue**2)[0:5]
    
    at = AnchoredText(txt_str, prop=dict(size=12), frameon=True, loc='lower right')
    
    at.patch.set_boxstyle("round, pad=0., rounding_size=0.2")
    ax.add_artist(at)
    
    plt.savefig(graph_file, dpi=300)
    plt.show()
    plt.close()
    
    return

