def format_traj(df_raw, coordinates, coordinates_short, movie_len, num_clusters):
    
    """
    Formats trajectories output from hierarchical clustering
    
    Args: 
        df_raw: (Dataframe) Data frame containing all input trajectories
        coordinates: (Dataframe) Dataframe of average xy-coordinates for each 
            short input trajectory
        coordinates_short: (Dataframe) Dataframe containing all average xy-
            coordiantes for each clustered trajectory shorter than the user
            specified minimum trajectory length
        movie_len: (int) Number of frames in movie
        num_clusters: (int) Number of clusters found
        
    Returns: 
        traj_array: (ndarray (movie_len, num_clusters*2)) Hierarchically
            clustered trajectories for each molecule whose linked
            trajectories met the user specified requirements
        
    """
    
    linked_traj_list = list()
    linked_traj_len_list = list()
    
    traj_array = np.zeros((movie_len, num_clusters*2))
    
    for i in range(num_clusters):
        linked_traj_long = pd.concat([df_raw[df_raw.id.isin(coordinates.index[coordinates['hc_label'] == i])]])
        linked_traj_short = pd.concat([df_raw[df_raw.id.isin(coordinates_short.index[coordinates_short['hc_label'] == i])]])
        linked_traj = pd.concat([linked_traj_long, linked_traj_short])
    
        linked_traj = linked_traj.sort_values(by=['id', 'frame_index'])
        linked_traj_list.append(linked_traj)
        linked_traj_len_list.append((len(linked_traj)))
    
        traj_mask = pd.DataFrame(np.nan, index=range(movie_len), columns=['x', 'y'])
        traj = linked_traj_list[i].set_index('frame_index')
        traj_filtered = traj[~traj.index.duplicated()] # filter the duplicated frame_index
        masked_traj = traj_filtered.reindex_like(traj_mask)
        traj_array[:, i*2:i*2+2] = masked_traj.to_numpy()
    
    trajarr_filepath = create_saveto_filepath(filename, '_raw_trajectories.csv')
    np.savetxt(trajarr_filepath, traj_array, delimiter=',')
    
    return traj_array

